const PROVINCE_BY_ID = new Map(PROVINCES.map((p) => [p.id, p]));

/** 저장용 키: "서울|강남구" */
export const regionKey = (provinceId: string, district: string) => `${provinceId}|${district}`;

export const ALL_REGION_KEYS: ReadonlySet<string> = new Set(
  PROVINCES.flatMap((p) => p.districts.map((d) => regionKey(p.id, d))),
);

export function isRegionKey(v: unknown): v is string {
  return typeof v === "string" && ALL_REGION_KEYS.has(v);
}

export function provinceOf(key: string): string {
  return key.split("|")[0];
}

/** 화면 표시용: "서울 강남구", 세종은 "세종" */
export function regionLabel(key: string): string {
  const [pid, district] = key.split("|");
  const p = PROVINCE_BY_ID.get(pid);
  if (!p || !district) return key;
  if (pid === "세종") return "세종";
  return `${p.label} ${district}`;
}

/** 시·도 하나에 속한 모든 키 */
export function provinceKeys(provinceId: string): string[] {
  const p = PROVINCE_BY_ID.get(provinceId);
  return p ? p.districts.map((d) => regionKey(p.id, d)) : [];
}
